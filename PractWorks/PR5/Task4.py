s = input("Строка: ")

if s.isdigit():
    print("Все символы в строке ЦИФРЫ")
elif s.isalpha():
    print("Все символы в строке БУКВЫ")
    if s.islower():
        print("Все буквы в строке в НИЖНЕМ регистре")
    elif s.isupper():
        print("Все буквы в строке в ВЕРХНЕМ регистре")
    else:
        print("В строке есть буквы обоих регистров")
else:
    print("Строка состоит из букв и цифр")